"""Volume button fix for the OneXPlayer Apex on SteamOS.

The Apex volume buttons emit KEY_VOLUMEUP and KEY_VOLUMEDOWN (scancodes 0xb0
and 0xae) on the built-in AT keyboard, isa0060/serio0. InputPlumber lists that
keyboard as a source device for the Apex and grabs it exclusively, so the
presses reach InputPlumber and stop there: Steam replaces the profile's
declared target devices with deck-uhid alone, leaving no keyboard target able
to re-emit them.

InputPlumber's source devices accept `passthrough`, documented in its schema as
"events will be read from this device, but the source device will not be hidden
or grabbed". Setting it on the AT keyboard leaves InputPlumber reading that
keyboard while the volume keys also reach the session, which is how SteamOS
already handles the AYANEO KUN and the MSI Claw.

The override is *derived* from whatever config InputPlumber currently ships
rather than carrying a copy of it, and the source file's hash is recorded in the
generated header so a SteamOS update that changes the shipped config can be
detected and the override rebuilt.
"""

import hashlib
import logging
import os
import subprocess

logger = logging.getLogger("OXP-VolumeButtons")

_log_info_cb = None
_log_error_cb = None
_log_warning_cb = None


def set_log_callbacks(info_fn, error_fn, warning_fn):
    global _log_info_cb, _log_error_cb, _log_warning_cb
    _log_info_cb = info_fn
    _log_error_cb = error_fn
    _log_warning_cb = warning_fn


def _log_info(msg):
    if _log_info_cb:
        _log_info_cb(msg)
    else:
        logger.info(msg)


def _log_error(msg):
    if _log_error_cb:
        _log_error_cb(msg)
    else:
        logger.error(msg)


def _log_warning(msg):
    if _log_warning_cb:
        _log_warning_cb(msg)
    else:
        logger.warning(msg)


def _clean_env():
    """Strip Decky's LD_LIBRARY_PATH/LD_PRELOAD for subprocess calls."""
    env = os.environ.copy()
    for var in ("LD_LIBRARY_PATH", "LD_PRELOAD"):
        env.pop(var, None)
    return env


_CONFIG_NAME = "50-onexplayer_apex.yaml"
# Shipped on the read-only root subvolume; the override directory is under /etc,
# which is an overlay backed by /var and writable as root.
_SHIPPED_PATH = f"/usr/share/inputplumber/devices/{_CONFIG_NAME}"
_OVERRIDE_DIR = "/etc/inputplumber/devices.d"
_OVERRIDE_PATH = f"{_OVERRIDE_DIR}/{_CONFIG_NAME}"

_UNIT = "inputplumber.service"

# The source device block to patch, and the option to add to it
_AT_KEYBOARD_KEY = "name: AT Translated Set 2 keyboard"
_OPTION = "passthrough: true"
_HASH_PREFIX = "# source-sha256: "

_HEADER = """# Generated by OneXPlayer Apex SteamOS Tools — do not edit by hand.
#
# Derived from {source}
{hash_line}
#
# The only change is `{option}` on the AT keyboard source device. The Apex
# volume buttons emit KEY_VOLUMEUP/KEY_VOLUMEDOWN (scancodes 0xb0/0xae) on
# isa0060/serio0, which InputPlumber grabs exclusively. Steam replaces this
# profile's target_devices with deck-uhid alone, so no keyboard target is left
# to re-emit them and the presses are swallowed. passthrough lets InputPlumber
# keep reading that keyboard without confiscating it.
"""


def _sha256(text):
    return hashlib.sha256(text.encode()).hexdigest()


def _patch(shipped_text):
    """Add the passthrough option to the AT keyboard source device.

    Text insertion rather than a YAML round-trip: the shipped file carries
    comments documenting the two firmware revisions, and losing them would make
    the override much harder to review against the original.

    Returns (text, note). `note` is set when nothing had to change, in which
    case the text is returned untouched. Raises ValueError if the source device
    that needs patching is not in the file at all.
    """
    lines = shipped_text.splitlines(keepends=True)

    marker = next((i for i, l in enumerate(lines) if _AT_KEYBOARD_KEY in l), None)
    if marker is None:
        raise ValueError(
            f"no '{_AT_KEYBOARD_KEY}' source device in {_SHIPPED_PATH} — "
            "InputPlumber's Apex config has changed shape"
        )

    # Walk back to the '- ' that opens this source device, so the whole list
    # item is considered and not just the keys under `evdev:`.
    start = marker
    while start > 0 and not lines[start].lstrip().startswith("- "):
        start -= 1
    item_indent = len(lines[start]) - len(lines[start].lstrip())
    option_indent = item_indent + 2

    # ...and forward to where the item ends: a blank line, or anything indented
    # no deeper than the item's own '- '.
    end = marker + 1
    while end < len(lines):
        line = lines[end]
        if not line.strip():
            break
        if (len(line) - len(line.lstrip())) <= item_indent:
            break
        end += 1

    if any(l.strip().startswith("passthrough:") for l in lines[start:end]):
        return shipped_text, "passthrough is already set in the shipped config"

    patched = lines[:end] + [" " * option_indent + _OPTION + "\n"] + lines[end:]
    return "".join(patched), None


def _build_override():
    """Read the shipped config and return (text, source_hash, note).

    `text` is None when the shipped config already does the right thing, in
    which case `note` explains why no override is needed.
    """
    with open(_SHIPPED_PATH) as f:
        shipped = f.read()
    body, note = _patch(shipped)
    source_hash = _sha256(shipped)
    if note:
        return None, source_hash, note
    header = _HEADER.format(
        source=_SHIPPED_PATH,
        hash_line=_HASH_PREFIX + source_hash,
        option=_OPTION,
    )
    return header + body, source_hash, None


def _recorded_hash():
    """The source hash the installed override was built from, if any."""
    try:
        with open(_OVERRIDE_PATH) as f:
            for line in f:
                if line.startswith(_HASH_PREFIX):
                    return line[len(_HASH_PREFIX):].strip()
                if not line.startswith("#"):
                    break
    except Exception:
        pass
    return None


def _current_hash():
    try:
        with open(_SHIPPED_PATH) as f:
            return _sha256(f.read())
    except Exception:
        return None


def is_applied():
    """Report whether the override is installed and still matches its source."""
    override_exists = os.path.exists(_OVERRIDE_PATH)
    shipped_exists = os.path.exists(_SHIPPED_PATH)
    recorded, current = _recorded_hash(), _current_hash()
    # Only meaningful when both are known; an override we did not generate has
    # no recorded hash and is left alone rather than reported as stale.
    stale = bool(override_exists and recorded and current and recorded != current)

    return {
        "applied": override_exists,
        "override_path": _OVERRIDE_PATH,
        "shipped_exists": shipped_exists,
        "stale": stale,
        "ours": bool(recorded),
    }


def _restart_inputplumber():
    """Restart InputPlumber so it re-reads its device configs."""
    try:
        r = subprocess.run(
            ["systemctl", "is-active", _UNIT],
            capture_output=True, text=True, timeout=10, env=_clean_env()
        )
        if r.stdout.strip() != "active":
            _log_info(f"{_UNIT} is not active — nothing to restart")
            return True
        r = subprocess.run(
            ["systemctl", "restart", _UNIT],
            capture_output=True, text=True, timeout=30, env=_clean_env()
        )
        if r.returncode == 0:
            _log_info(f"Restarted {_UNIT}")
            return True
        _log_error(f"Failed to restart {_UNIT}: {r.stderr.strip()}")
        return False
    except Exception as e:
        _log_error(f"InputPlumber restart failed: {e}")
        return False


def apply():
    """Install the override and restart InputPlumber."""
    steps = []
    _log_info("=== Volume Buttons Apply Start ===")

    if not os.path.exists(_SHIPPED_PATH):
        msg = f"{_SHIPPED_PATH} not found — is InputPlumber installed?"
        _log_error(msg)
        return {"success": False, "error": msg, "steps": steps}

    try:
        text, source_hash, note = _build_override()
    except ValueError as e:
        _log_error(f"Cannot build override: {e}")
        return {"success": False, "error": str(e), "steps": steps}
    except Exception as e:
        _log_error(f"Failed to read {_SHIPPED_PATH}: {e}")
        return {"success": False, "error": str(e), "steps": steps}

    if text is None:
        # A future InputPlumber may ship the fix itself. Nothing to install, and
        # that is the good outcome rather than a failure.
        _log_info(f"No override needed — {note}")
        steps.append(note)
        return {"success": True, "message": "Already handled by InputPlumber", "steps": steps}

    steps.append(f"Derived override from {_SHIPPED_PATH} ({source_hash[:12]})")

    try:
        os.makedirs(_OVERRIDE_DIR, mode=0o755, exist_ok=True)
        with open(_OVERRIDE_PATH, "w") as f:
            f.write(text)
        os.chmod(_OVERRIDE_PATH, 0o644)
        _log_info(f"Wrote {_OVERRIDE_PATH}")
        steps.append("Wrote the InputPlumber override")
    except Exception as e:
        _log_error(f"Failed to write {_OVERRIDE_PATH}: {e}")
        return {"success": False, "error": f"Failed to write override: {e}", "steps": steps}

    if not _restart_inputplumber():
        steps.append("Override written, but InputPlumber did not restart")
        return {
            "success": False,
            "error": "Override written but InputPlumber failed to restart — reboot to apply",
            "steps": steps,
        }
    steps.append("Restarted InputPlumber")

    _log_info("Volume buttons fix applied")
    return {"success": True, "message": "Volume buttons enabled", "steps": steps}


def revert():
    """Remove the override and restart InputPlumber."""
    steps = []
    _log_info("=== Volume Buttons Revert Start ===")

    if os.path.exists(_OVERRIDE_PATH):
        if not _recorded_hash():
            # Someone else's file living at our path: refuse rather than delete
            # a config we cannot prove we wrote.
            msg = f"{_OVERRIDE_PATH} was not generated by this plugin — leaving it alone"
            _log_warning(msg)
            return {"success": False, "error": msg, "steps": steps}
        try:
            os.remove(_OVERRIDE_PATH)
            _log_info(f"Removed {_OVERRIDE_PATH}")
            steps.append("Removed the InputPlumber override")
        except Exception as e:
            _log_error(f"Failed to remove {_OVERRIDE_PATH}: {e}")
            return {"success": False, "error": str(e), "steps": steps}
    else:
        steps.append("No override to remove")

    _restart_inputplumber()
    steps.append("Restarted InputPlumber")

    _log_info("Volume buttons fix reverted")
    return {"success": True, "message": "Volume buttons reverted", "steps": steps}


def refresh_if_stale():
    """Rebuild the override if SteamOS has since changed the shipped config.

    Called on plugin start. Without this, a SteamOS update that adds a firmware
    revision or fixes the paddle mapping would be silently masked by our older
    copy.
    """
    status = is_applied()
    if not status["applied"] or not status["stale"]:
        return {"refreshed": False, "reason": "nothing to do"}

    _log_warning(
        f"{_SHIPPED_PATH} changed since the override was built — rebuilding it"
    )
    result = apply()
    return {"refreshed": bool(result.get("success")), "result": result}
